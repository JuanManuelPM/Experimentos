#!/usr/bin/env python3
"""SALA DE CONTROL: deterministic original multitrack demo and mixing lab.
All sound is generated by this source; no third-party samples or presets.
Requires numpy, scipy, soundfile. Usage: python render.py --mode first|full --out DIR
"""
import argparse, json, math, pathlib
import numpy as np
import soundfile as sf
from scipy.signal import butter, sosfilt, lfilter

SR=48000; BPM=104; BEAT=60/BPM; BAR=BEAT*4; SEED=203710
ROOTS=[48,44,51,46,48,44]  # C3 Ab2 Eb3 Bb2, ordered through the song
CHORDS=[[60,63,67,70,74],[56,60,63,67,70],[63,67,70,74,77],[58,62,65,69,72]]
STEM_NAMES=['drums','bass','keys','melody','atmosphere']

def hz(midi): return 440*2**((midi-69)/12)
def filter_sig(x,lo=None,hi=None):
    if lo and hi: typ='bandpass'; wn=[lo,hi]
    elif lo: typ='highpass'; wn=lo
    else: typ='lowpass'; wn=hi
    return sosfilt(butter(2,wn,btype=typ,fs=SR,output='sos'),x).astype('float32')
def place(dst,sound,sec,pan=0):
    i=int(sec*SR)
    if i>=len(dst) or i+len(sound)<=0:return
    j=min(len(dst),i+len(sound)); src=sound[:j-i]
    # pan equal power
    dst[i:j,0]+=src*math.cos((pan+1)*math.pi/4)
    dst[i:j,1]+=src*math.sin((pan+1)*math.pi/4)

def kick():
    t=np.arange(int(.68*SR),dtype=np.float32)/SR
    phase=2*np.pi*(49*t + 102*(1-np.exp(-t*35))/35)
    body=np.sin(phase)*np.exp(-t*9.0)
    tick=np.sin(2*np.pi*1650*t)*np.exp(-t*110)
    return (body+.095*tick).astype('float32')
def snare(rng):
    t=np.arange(int(.32*SR),dtype=np.float32)/SR
    n=filter_sig(rng.standard_normal(t.shape).astype('float32'),lo=900,hi=8300)
    return (.12*n*np.exp(-t*15)+.08*np.sin(2*np.pi*178*t)*np.exp(-t*24)).astype('float32')
def hat(rng,long=False):
    t=np.arange(int((.26 if long else .11)*SR),dtype=np.float32)/SR
    noise=filter_sig(rng.standard_normal(t.shape).astype('float32'),lo=6200)
    return (.18*noise*np.exp(-t*(21 if long else 61))).astype('float32')
def bass_note(midi,dur):
    t=np.arange(int(dur*SR),dtype=np.float32)/SR
    f=hz(midi); env=(1-np.exp(-t*190))*np.exp(-t*3.25)
    # harmonic, rounded bass without unbounded sub
    y=(.80*np.sin(2*np.pi*f*t)+.16*np.sin(2*np.pi*(2*f)*t)+.07*np.sin(2*np.pi*(3*f)*t))*env
    return (y*.53).astype('float32')
def key_note(midi,dur,velocity=1.):
    t=np.arange(int(dur*SR),dtype=np.float32)/SR
    f=hz(midi)
    op=np.sin(2*np.pi*(2*f)*t)*np.exp(-t*5)
    y=np.sin(2*np.pi*f*t+1.35*op)+.16*np.sin(2*np.pi*(3*f)*t)
    env=(1-np.exp(-t*180))*(.3*np.exp(-t*.6)+.7*np.exp(-t*3.5))
    return (.105*velocity*y*env).astype('float32')
def mallet(midi,dur):
    t=np.arange(int(dur*SR),dtype=np.float32)/SR
    f=hz(midi)
    y=np.sin(2*np.pi*f*t)+.23*np.sin(2*np.pi*f*2.01*t)*np.exp(-t*4)+.11*np.sin(2*np.pi*f*4.04*t)*np.exp(-t*7)
    return (.21*y*(1-np.exp(-t*175))*np.exp(-t*2.3)).astype('float32')
def make_track(bars=24):
    rng=np.random.default_rng(SEED)
    n=int((bars*BAR+.8)*SR)
    tracks={s:np.zeros((n,2),np.float32) for s in STEM_NAMES}
    k=kick()
    for b in range(bars):
        base=b*BAR
        is_break=(bars==24 and 12<=b<=15)
        is_intro=b<4
        is_outro=bars==24 and b>=20
        chord=CHORDS[(b//4)%4]
        root=ROOTS[(b//4)%len(ROOTS)]
        for beat in range(4):
            ts=base+beat*BEAT
            if not (is_break and beat in [1,3]) and (not is_intro or beat in [0,2]):
                place(tracks['drums'],k*(.64 if is_break else .77),ts,0)
            if not is_break and (beat in [1,3]):
                place(tracks['drums'],snare(rng)*(.75 if b<4 else 1),ts+.003+(b%2)*.004,pan=.02)
            if not is_intro and not is_break:
                for h in range(2):
                    if (b+beat+h)%7!=0:
                        place(tracks['drums'],hat(rng,long=(beat==3 and h==1))*(.30 if h else .19),ts+h*BEAT/2+(h*.012),pan=.34 if h else -.35)
            if b>=4 and b<20 and not is_break and beat in [1,3] and b%2==1:
                place(tracks['drums'],snare(rng)*.12,ts+BEAT*.72,pan=-.20)
        if not is_intro or b>=2:
            seq=[(0,root,BEAT*.74),(1.5,root+7,BEAT*.45),(2.5,root+12,BEAT*.62),(3.4,root+7,BEAT*.37)]
            if is_break: seq=[(0,root,BEAT*.92),(2.8,root+12,BEAT*.53)]
            for j,(p,note,dur) in enumerate(seq):
                place(tracks['bass'], bass_note(note,dur)*(.85 if is_break else 1),base+p*BEAT,0)
        if b<22:
            for j,note in enumerate(chord):
                start=base+(.03+j*.032)*BEAT
                if b>=4 and not is_break: start+= (0 if b%2 else .125*BEAT)
                place(tracks['keys'],key_note(note,2.65*BEAT,velocity=(.77 if is_intro else .94)) ,start,pan=(-.66+.33*j))
            if not is_break and b>=4:
                for idx,note in enumerate([chord[-2],chord[1]]):
                    place(tracks['keys'],key_note(note+12,BEAT*.55,.25),base+(2.25+idx*.6)*BEAT,pan=.4 if idx else -.4)
        if b>=4 and b<22:
            phrase=[(0.3,75),(1.20,74),(2.25,70),(3.25,67)] if (b//2)%2==0 else [(0.75,72),(1.4,70),(2.7,75)]
            if is_break: phrase=[(1.0,79),(3.00,75)]
            for j,(p,note) in enumerate(phrase):
                transpose=[0,-4,3,-2][(b//4)%4]
                place(tracks['melody'],mallet(note+transpose,BEAT*1.30)*(0.64 if is_break else .85),base+p*BEAT,pan=(-.5 if j%2 else .48))
    # atmosphere is purely synthesized harmonic wash + filtered original noise with echoes
    t=np.arange(n,dtype=np.float32)/SR
    noise=filter_sig(rng.standard_normal(n).astype('float32'),lo=1000,hi=5100)
    # slow envelopes and periodic risers, independently authored sound
    phase=np.mod(t/BAR,4)
    amp=.012+.013*(np.sin(2*np.pi*t/(BAR*8))**2)
    air=noise*amp*(.70+.3*np.sin(2*np.pi*phase/4))
    air=filter_sig(air,hi=5500)
    tracks['atmosphere'][:,0]+=air*.8
    tracks['atmosphere'][:,1]+=(np.roll(air,int(.017*SR))*.75)
    # echo on melody (within its stem for stem/mix consistency)
    m=tracks['melody'].copy()
    for delay,amt in [(.375,.16),(.75,.09)]:
        ofs=int(delay*SR)
        tracks['melody'][ofs:]+=(m[:-ofs]*amt)
    # intro/outro fades strictly on stems so sum is exact
    total_t=np.arange(n,dtype=np.float32)/SR
    f=np.minimum(1,total_t/.58)*np.minimum(1,np.maximum(0,(len(t)/SR-total_t)/1.20))
    for a in tracks.values():a*=f[:,None]
    return tracks

def splitmix(tracks,revision=False):
    if revision:
        gains={'drums':1.06,'bass':.83,'keys':.74,'melody':1.10,'atmosphere':.68}
    else:
        gains={'drums':.87,'bass':1.11,'keys':1.11,'melody':.77,'atmosphere':1.05}
    # source stem treated identically by mix and exported, outputs derived from these stems
    mix=np.zeros_like(tracks['bass'])
    for name,x in tracks.items():
        z=x.copy()
        if name=='bass':
            if revision:
                z[:,0]=(x[:,0]+x[:,1])*.5
                z[:,1]=z[:,0] # preserve mono low end
                # controlled bass masked less by kick due to stem gain/EQ
            else:
                z[:,1]=x[:,1]*.78  # documented L/R imbalance in base
        if name=='keys':
            if revision:
                # reduce low mid energy; cleaner space for bass, true EQ not global gain
                lows=filter_sig(x[:,0],hi=460),filter_sig(x[:,1],hi=460)
                z[:,0]-=lows[0]*.33
                z[:,1]-=lows[1]*.33
            else:
                z+=.22*np.roll(z,180,axis=0)  # subtle excess smearing baseline
        if name=='drums' and revision:
            # soften extreme hat range while preserving kick transient
            hi0=filter_sig(z[:,0],lo=7000); hi1=filter_sig(z[:,1],lo=7000)
            z[:,0]-=.20*hi0; z[:,1]-=.20*hi1
        mix+=z*gains[name]
    return mix*.83, gains

def true_peak(x):
    from scipy.signal import resample_poly
    return float(np.max(np.abs(resample_poly(x,4,1,axis=0))))

def master_revision(x):
    # short-time envelope compressor, transparent soft limiter
    from scipy.ndimage import maximum_filter1d, gaussian_filter1d
    env=np.max(np.abs(x),axis=1)
    env=maximum_filter1d(env,size=1921)
    env=gaussian_filter1d(env,sigma=400)
    gain=np.minimum(1, (.51/np.maximum(env,1e-5))**.30)
    out=np.tanh(x*gain[:,None]*1.38)/1.38
    return out.astype(np.float32)

def write(path,x):
    sf.write(str(path),np.clip(x,-.995,.995),SR,subtype='PCM_24')

def main():
    p=argparse.ArgumentParser();p.add_argument('--mode',choices=['first','full'],default='full');p.add_argument('--out',default='assets')
    a=p.parse_args();out=pathlib.Path(a.out);out.mkdir(parents=True,exist_ok=True)
    bars=6 if a.mode=='first' else 24
    tracks=make_track(bars)
    if a.mode=='first':
        # Risk-first spike: use an active arrangement with rhythm, bass and all instruments.
        i=int(4*BAR*SR)
        tracks={name:stem[i:].copy() for name,stem in tracks.items()}
    base,gbase=splitmix(tracks,False)
    rev,grev=splitmix(tracks,True)
    # Match integrated level later via EBU measurement; preserve unmodified raws in project
    if a.mode=='first':
        write(out/'FIRST_ARTICLE_mix.wav',rev)
        print(json.dumps({'firstArticle':'rendered','lengthSec':len(rev)/SR,'samplePeak':float(np.max(np.abs(rev))), 'stereoDifference':float(np.mean(np.abs(rev[:,0]-rev[:,1]))), 'signature':SEED},indent=2))
        return
    master=master_revision(rev)
    for name,x in tracks.items():write(out/('stem_'+name+'.wav'),x)
    for name,x in [('base_raw',base),('revised_raw',rev),('master_raw',master)]:write(out/(name+'.wav'),x)
    json.dump({'title':'SALA DE CONTROL','source':'original algorithmic synth, no third party audio','sampleRate':SR,'bpm':BPM,'bars':bars,'seed':SEED,'stemNames':STEM_NAMES,'mixBaseGains':gbase,'mixRevisedGains':grev,'signalPath':['stems original','base/revised processing from stems','master from revised'],'nominalLengthSec':len(master)/SR,'samplePeakRaw':{name:float(np.max(np.abs(x))) for name,x in [('base',base),('revised',rev),('master',master)]}},open(out.parent/'session.json','w'),indent=2)
    print('source rendered',bars,'bars',len(master)/SR,'sec')
if __name__=='__main__':main()
