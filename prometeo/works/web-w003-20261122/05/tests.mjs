import assert from 'node:assert/strict';
import {CATALOG,sanitizeCart,updateCart,summarizeCart,readCart,writeCart,STORAGE_KEY} from './cart-core.js';
let cart={};for(const id of Object.keys(CATALOG))cart=updateCart(cart,{type:'ADD',id});
assert.equal(summarizeCart(cart).count,3,'all three variants counted');
assert.equal(summarizeCart(cart).total,249000+259000+269000,'variant prices summed');
cart=updateCart(cart,{type:'SET',id:'arcilla',quantity:4});
assert.equal(summarizeCart(cart).total,249000+4*259000+269000,'quantity updates total');
cart=updateCart(cart,{type:'REMOVE',id:'noche'});assert.equal(summarizeCart(cart).count,5,'remove preserves other variants');
assert.deepEqual(sanitizeCart({tiza:-9,arcilla:1.3,noche:999,evil:123}),{noche:20},'reject invalid and cap maximum');
assert.deepEqual(sanitizeCart({__proto__:12,arcilla:'5'}),{},'reject types');
assert.deepEqual(updateCart(cart,{type:'ADD',id:'inventado'}),cart,'unknown SKU ignored');
assert.deepEqual(updateCart(cart,{type:'CLEAR'}),{},'explicit clear');
const mem=new Map();const storage={getItem:k=>mem.get(k)||null,setItem:(k,v)=>mem.set(k,v)};
assert.equal(writeCart(storage,cart),true);assert.deepEqual(readCart(storage),cart,'reload persistence');
mem.set(STORAGE_KEY,'{bad');assert.deepEqual(readCart(storage),{},'malformed storage safe');
assert.deepEqual(readCart({getItem(){throw Error('disabled')}}),{},'storage access denied safely');
assert.equal(writeCart({setItem(){throw Error('disabled')}},cart),false,'write denial nonfatal');
assert.deepEqual(updateCart({tiza:1},{type:'SET',id:'tiza',quantity:0}),{},'zero quantity removes line');
console.log('13 / 13 commerce assertions PASS');
