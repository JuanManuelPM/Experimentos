import {readFileSync} from 'node:fs';
import {firstArticleCut,inspectEyelineAxis} from './continuity.mjs';
import {validateTimeline,evaluateTimeline,diffAt,retimeShot} from './sequencer.mjs';
const check=(condition,reason)=>{if(!condition)throw Error(reason)};
const film=JSON.parse(readFileSync(new URL('./timeline.json',import.meta.url)));
const article=firstArticleCut(film);
check(!validateTimeline(film).length,'original timeline invalid');
check(!validateTimeline(article).length,'article timeline invalid');
check(article.shots.length===2&&article.duration===3.2,'first article duration');
check(evaluateTimeline(1.599,article).shotId==='fa01','first shot boundary');
check(evaluateTimeline(1.6,article).shotId==='fa02','second shot boundary');
check(inspectEyelineAxis(article).ok,'2 shot eye axis fails');
check(inspectEyelineAxis(film).ok,'5 shot eye axis fails');
for(let i=0;i<=64;i++)check(diffAt(film,JSON.parse(JSON.stringify(film)),film.duration*i/64)===0,'non deterministic sample '+i);
const retimed=retimeShot(film,film.shots[1].id,6.25);
check(!validateTimeline(retimed).length,'retime invalid');
const illegal=JSON.parse(JSON.stringify(article));illegal.shots[1].camera.from[2]=-1;
check(!inspectEyelineAxis(illegal).ok,'crossing camera axis was not rejected');
console.log('PASS 10 assertions/steps · W7-04: timeline, continuity, cut, retime, boundaries');
